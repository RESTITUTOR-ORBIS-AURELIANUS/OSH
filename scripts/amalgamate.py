#!/usr/bin/env python3
"""Build the self-contained submission from maintained source files."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
seen = set()
def expand(path):
    path = path.resolve()
    if path in seen:
        return ""
    seen.add(path)
    parts = ["\n// ===== " + str(path.relative_to(ROOT)) + " =====\n"]
    for line in path.read_text().splitlines(keepends=True):
        match = re.fullmatch(r'#include "([^\"]+)"\s*', line)
        if match:
            parts.append(expand(path.parent / match.group(1)))
        elif line.strip() != "#pragma once":
            parts.append(line)
    return "".join(parts)
output = ROOT / "submission.cpp"
output.write_text("// Generated by scripts/amalgamate.py; edit pager.cpp / include/*.hpp.\n" + expand(ROOT / "pager.cpp"))
print(output)
